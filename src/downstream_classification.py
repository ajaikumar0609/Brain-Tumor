"""Downstream classification: real-only vs real + conditional-GAN synthetic training data.

    python src/downstream_classification.py --out-dir outputs/downstream_classification
    python src/downstream_classification.py --smoke --out-dir <scratch>      # tiny wiring test

Design (identical for both conditions; only the training set differs):
  * archive/Training is split ONCE, stratified 80/20 (split seed 42): 4,480 train / 1,120 validation real images.
  * Condition "real_only": train on the 4,480 real training images.
    Condition "real_plus_cwgangp": the same real images + N synthetic images per class generated by the
    cWGAN-GP checkpoint (3,000 updates) and labelled with the label they were GENERATED FOR. Whether those
    images really depict the class is unverified (see the GAN evaluation), so this tests usefulness, not correctness.
  * Validation set is real-only for both conditions and is used for checkpoint (best-epoch) selection.
  * archive/Testing is read only after training, once per run, to evaluate the validation-selected weights.
    It is never used for training, augmentation choice, checkpoint selection or hyperparameters.
  * Unconditional DCGAN / WGAN-GP samples are NOT used (they carry no class label).
  * Same small CNN, Adam lr 1e-3, batch 64, no data augmentation, 64x64 grayscale in [-1, 1], same seeds for both.
"""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
import sys
import time
from pathlib import Path

import numpy as np
import torch
import torch.nn as nn
import torch.nn.functional as F
from PIL import Image
from torchvision import transforms

from cwgangp_train import CondGenerator

ROOT = Path(__file__).resolve().parent.parent
CLASSES = ["glioma", "meningioma", "notumor", "pituitary"]
IMAGE_EXTS = {".jpg", ".jpeg", ".png", ".bmp"}
TF = transforms.Compose([transforms.Grayscale(num_output_channels=1), transforms.Resize((64, 64)), transforms.ToTensor()])
GAN_CKPT = ROOT / "outputs/cwgangp_3000/checkpoint_step_3000.pth"
SPLIT_SEED = 42
SYN_SEED = 3001


def load_images(split_dir: Path, per_class: int | None = None):
    imgs, labels, paths = [], [], []
    for c, name in enumerate(CLASSES):
        files = sorted(p for p in (split_dir / name).iterdir() if p.suffix.lower() in IMAGE_EXTS)
        if per_class:
            files = files[:per_class]
        for p in files:
            with Image.open(p) as im:
                imgs.append((TF(im) * 255).round().to(torch.uint8))
            labels.append(c)
            paths.append(str(p.relative_to(split_dir)))
    return torch.stack(imgs), torch.tensor(labels), paths


def stratified_split(labels: torch.Tensor, val_frac: float, seed: int):
    rng = np.random.RandomState(seed)
    tr, va = [], []
    for c in range(len(CLASSES)):
        idx = (labels == c).nonzero().squeeze(1).numpy()
        rng.shuffle(idx)
        k = int(round(len(idx) * val_frac))
        va += idx[:k].tolist()
        tr += idx[k:].tolist()
    return sorted(tr), sorted(va)


@torch.no_grad()
def make_synthetic(per_class: int, device, ck: dict) -> tuple[torch.Tensor, torch.Tensor]:
    assert ck["gen_updates"] == 3000, "unexpected cWGAN-GP checkpoint"
    G = CondGenerator()
    G.load_state_dict(ck["G"])
    G = G.to(device).eval()
    y = torch.arange(len(CLASSES)).repeat_interleave(per_class)
    z = torch.randn(len(y), 100, generator=torch.Generator().manual_seed(SYN_SEED))
    out = torch.cat([G(z[i:i + 200].to(device), y[i:i + 200].to(device)).cpu() for i in range(0, len(y), 200)])
    return ((out.clamp(-1, 1) + 1) / 2 * 255).round().to(torch.uint8), y        # same uint8 storage as real images


class SmallCNN(nn.Module):
    def __init__(self, n_classes: int = 4):
        super().__init__()
        def block(i, o):
            return nn.Sequential(nn.Conv2d(i, o, 3, padding=1, bias=False), nn.BatchNorm2d(o), nn.ReLU(True), nn.MaxPool2d(2))
        self.features = nn.Sequential(block(1, 32), block(32, 64), block(64, 128), block(128, 256))   # 64 -> 4
        self.head = nn.Sequential(nn.Dropout(0.3), nn.Linear(256, n_classes))

    def forward(self, x):
        return self.head(self.features(x).mean(dim=(2, 3)))


def norm(u8: torch.Tensor, device) -> torch.Tensor:
    return (u8.float().to(device) / 255 - 0.5) / 0.5


@torch.no_grad()
def predict(model, x_u8, device, bs=256) -> torch.Tensor:
    model.eval()
    return torch.cat([model(norm(x_u8[i:i + bs], device)).argmax(1).cpu() for i in range(0, len(x_u8), bs)])


def metrics(y_true: torch.Tensor, y_pred: torch.Tensor) -> dict:
    from sklearn.metrics import classification_report, confusion_matrix
    rep = classification_report(y_true, y_pred, labels=list(range(4)), target_names=CLASSES, output_dict=True, zero_division=0)
    return {"accuracy": rep["accuracy"], "macro_f1": rep["macro avg"]["f1-score"], "weighted_f1": rep["weighted avg"]["f1-score"],
            "per_class": {c: {k: rep[c][k] for k in ("precision", "recall", "f1-score", "support")} for c in CLASSES},
            "confusion_matrix": confusion_matrix(y_true, y_pred, labels=list(range(4))).tolist()}


def train_one(condition: str, seed: int, xtr, ytr, xva, yva, load_test, epochs: int, device) -> dict:
    torch.manual_seed(seed)
    model = SmallCNN().to(device)
    opt = torch.optim.Adam(model.parameters(), 1e-3)
    best = {"val_acc": -1.0, "val_loss": 1e9, "epoch": -1, "state": None}
    g = torch.Generator().manual_seed(seed)
    t0 = time.perf_counter()
    hist = []
    for ep in range(1, epochs + 1):
        model.train()
        perm = torch.randperm(len(xtr), generator=g)
        tot = 0.0
        for i in range(0, len(perm) - 63, 64):
            idx = perm[i:i + 64]
            loss = F.cross_entropy(model(norm(xtr[idx], device)), ytr[idx].to(device))
            opt.zero_grad()
            loss.backward()
            if not torch.isfinite(loss).item():
                raise FloatingPointError(f"non-finite loss {condition} seed {seed} epoch {ep}")
            opt.step()
            tot += loss.item()
        model.eval()
        with torch.no_grad():
            logits = torch.cat([model(norm(xva[i:i + 256], device)).cpu() for i in range(0, len(xva), 256)])
        vl, va = F.cross_entropy(logits, yva).item(), (logits.argmax(1) == yva).float().mean().item()
        hist.append({"epoch": ep, "train_loss": tot / max(len(perm) // 64, 1), "val_loss": vl, "val_acc": va})
        if va > best["val_acc"] or (va == best["val_acc"] and vl < best["val_loss"]):
            best = {"val_acc": va, "val_loss": vl, "epoch": ep, "state": {k: v.detach().cpu().clone() for k, v in model.state_dict().items()}}
    train_seconds = time.perf_counter() - t0
    model.load_state_dict(best["state"])
    xte, yte = load_test()                                                   # Testing read here, after selection
    res = metrics(yte, predict(model, xte, device))
    return {"condition": condition, "seed": seed, "n_train": len(xtr), "n_val": len(xva), "n_test": len(xte),
            "best_epoch": best["epoch"], "best_val_acc": best["val_acc"], "train_seconds": round(train_seconds, 1),
            "history": hist, "test": res}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out-dir", type=Path, default=ROOT / "outputs/downstream_classification")
    ap.add_argument("--seeds", type=int, nargs="+", default=[42, 43, 44])
    ap.add_argument("--epochs", type=int, default=15)
    ap.add_argument("--synthetic-per-class", type=int, default=1400)
    ap.add_argument("--gan-ckpt", type=Path, default=GAN_CKPT, help="cWGAN-GP checkpoint used to create the synthetic images")
    ap.add_argument("--write-split-lists", type=Path, default=None, metavar="DIR",
                    help="write cnn_train_files.json / cnn_val_files.json (the CNN split) to DIR and exit")
    ap.add_argument("--require-leakage-free", action="store_true",
                    help="abort unless the GAN was trained on files disjoint from the CNN validation set")
    ap.add_argument("--smoke", action="store_true", help="tiny wiring test: 40 train imgs/class, 1 epoch, 1 seed, 50 synthetic/class")
    ap.add_argument("--device", choices=["auto", "mps", "cpu"], default="auto")
    args = ap.parse_args()
    if (args.out_dir / "summary.json").exists() and not args.write_split_lists:
        print(f"ERROR: {args.out_dir}/summary.json exists; refusing to overwrite (choose another --out-dir)", file=sys.stderr)
        return 2
    device = torch.device("mps" if args.device in ("auto", "mps") and torch.backends.mps.is_available() else "cpu")
    per_class_cap = 40 if args.smoke else None
    if args.smoke:
        args.seeds, args.epochs, args.synthetic_per_class = args.seeds[:1], 1, 50
    x_all, y_all, paths = load_images(ROOT / "archive/Training", per_class_cap)
    tr, va = stratified_split(y_all, 0.2, SPLIT_SEED)
    if args.write_split_lists:
        args.write_split_lists.mkdir(parents=True, exist_ok=True)
        (args.write_split_lists / "cnn_train_files.json").write_text(json.dumps(sorted(paths[i] for i in tr), indent=0))
        (args.write_split_lists / "cnn_val_files.json").write_text(json.dumps(sorted(paths[i] for i in va), indent=0))
        print(f"wrote CNN split lists to {args.write_split_lists}: train={len(tr)} val={len(va)}")
        return 0
    xtr_real, ytr_real, xva, yva = x_all[tr], y_all[tr], x_all[va], y_all[va]
    # ---- leakage audit: which files did the synthetic-image GAN train on? ----
    ck = torch.load(args.gan_ckpt, map_location="cpu", weights_only=True)
    tl = ck["config"].get("train_list")
    if tl:
        tl_path = Path(tl) if Path(tl).is_absolute() else ROOT / tl
        gan_files = set(json.loads(tl_path.read_text()))
        gan_scope = f"train list {tl} (sha256 {ck['config'].get('train_list_sha256')})"
    else:
        gan_files = set(paths)                       # no list recorded: the GAN trained on all of archive/Training
        gan_scope = "ALL images in archive/Training (no train list recorded in the checkpoint)"
    val_paths, train_paths = {paths[i] for i in va}, {paths[i] for i in tr}
    audit = {"gan_checkpoint": str(args.gan_ckpt), "gan_training_scope": gan_scope, "gan_training_images": len(gan_files),
             "gan_overlap_with_cnn_validation": len(gan_files & val_paths), "gan_overlap_with_cnn_training": len(gan_files & train_paths),
             "gan_saw_archive_testing": False, "leakage_free": len(gan_files & val_paths) == 0}
    print("leakage audit:", json.dumps(audit))
    if args.require_leakage_free and not audit["leakage_free"]:
        print("ERROR: GAN training data overlaps the CNN validation set; refusing (--require-leakage-free)", file=sys.stderr)
        return 4
    (args.out_dir / "runs").mkdir(parents=True, exist_ok=True)
    xsyn, ysyn = make_synthetic(args.synthetic_per_class, device, ck)
    test_cache = {}

    def load_test():
        if "d" not in test_cache:
            x, y, _ = load_images(ROOT / "archive/Testing", 100 if args.smoke else None)
            test_cache["d"] = (x, y)
        return test_cache["d"]

    config = {"split_seed": SPLIT_SEED, "run_seeds": args.seeds, "epochs": args.epochs, "optimizer": "Adam lr=1e-3, batch 64",
              "augmentation": "none", "model": "SmallCNN (4 conv blocks 32-64-128-256, GAP, dropout 0.3)", "device": str(device),
              "n_train_real": len(xtr_real), "n_val_real": len(xva), "synthetic_per_class": args.synthetic_per_class,
              "synthetic_source": str(args.gan_ckpt), "synthetic_seed": SYN_SEED, "leakage_audit": audit,
              "leakage_free": audit["leakage_free"],
              "synthetic_labels": "the label each image was generated for; correctness unverified",
              "train_val_file_list_sha256": hashlib.sha256("\n".join(paths).encode()).hexdigest(),
              "test_dir": "archive/Testing (read only after training; never used for selection)", "smoke": args.smoke,
              "torch_version": str(torch.__version__)}
    (args.out_dir / "config.json").write_text(json.dumps(config, indent=2))
    print(f"device={device} train_real={len(xtr_real)} val={len(xva)} synthetic={len(xsyn)}")

    conditions = {"real_only": (xtr_real, ytr_real),
                  "real_plus_cwgangp_synthetic": (torch.cat([xtr_real, xsyn]), torch.cat([ytr_real, ysyn]))}
    runs = []
    for cond, (x, y) in conditions.items():
        for seed in args.seeds:
            r = train_one(cond, seed, x, y, xva, yva, load_test, args.epochs, device)
            (args.out_dir / "runs" / f"{cond}_seed{seed}.json").write_text(json.dumps(r, indent=2))
            runs.append(r)
            print(f"{cond} seed {seed}: n_train={r['n_train']} best_epoch={r['best_epoch']} val_acc={r['best_val_acc']:.4f} "
                  f"test_acc={r['test']['accuracy']:.4f} macroF1={r['test']['macro_f1']:.4f} ({r['train_seconds']}s)")

    summary = {"config": config, "conditions": {}}
    for cond in conditions:
        rs = [r for r in runs if r["condition"] == cond]
        agg = {}
        for k in ("accuracy", "macro_f1", "weighted_f1"):
            v = np.array([r["test"][k] for r in rs])
            agg[k] = {"mean": float(v.mean()), "std": float(v.std(ddof=1)) if len(v) > 1 else None, "values": v.tolist()}
        agg["per_class_f1_mean"] = {c: float(np.mean([r["test"]["per_class"][c]["f1-score"] for r in rs])) for c in CLASSES}
        agg["per_class_recall_mean"] = {c: float(np.mean([r["test"]["per_class"][c]["recall"] for r in rs])) for c in CLASSES}
        agg["per_class_precision_mean"] = {c: float(np.mean([r["test"]["per_class"][c]["precision"] for r in rs])) for c in CLASSES}
        agg["mean_confusion_matrix"] = np.mean([r["test"]["confusion_matrix"] for r in rs], axis=0).tolist()
        agg["n_train"] = rs[0]["n_train"]
        agg["n_runs"] = len(rs)
        summary["conditions"][cond] = agg
    a, b = summary["conditions"]["real_only"]["accuracy"]["values"], summary["conditions"]["real_plus_cwgangp_synthetic"]["accuracy"]["values"]
    summary["paired_accuracy_difference_synthetic_minus_real_only"] = {"per_seed": [y - x for x, y in zip(a, b)],
                                                                         "mean": float(np.mean(np.array(b) - np.array(a)))}
    (args.out_dir / "summary.json").write_text(json.dumps(summary, indent=2))
    with open(args.out_dir / "summary.csv", "w", newline="") as f:
        w = csv.writer(f)
        w.writerow(["condition", "n_train", "n_runs", "test_accuracy_mean", "test_accuracy_std", "macro_f1_mean", "macro_f1_std", "weighted_f1_mean"] +
                   [f"f1_{c}" for c in CLASSES])
        for cond, s in summary["conditions"].items():
            w.writerow([cond, s["n_train"], s["n_runs"], s["accuracy"]["mean"], s["accuracy"]["std"], s["macro_f1"]["mean"], s["macro_f1"]["std"],
                        s["weighted_f1"]["mean"]] + [s["per_class_f1_mean"][c] for c in CLASSES])
    with open(args.out_dir / "classification_report.txt", "w") as f:
        for cond, s in summary["conditions"].items():
            f.write(f"== {cond} (mean over {s['n_runs']} seeds; n_train={s['n_train']}) ==\n")
            f.write(f"accuracy {s['accuracy']['mean']:.4f}  macro-F1 {s['macro_f1']['mean']:.4f}  weighted-F1 {s['weighted_f1']['mean']:.4f}\n")
            for c in CLASSES:
                f.write(f"  {c:11s} P {s['per_class_precision_mean'][c]:.4f}  R {s['per_class_recall_mean'][c]:.4f}  F1 {s['per_class_f1_mean'][c]:.4f}\n")
            f.write("  mean confusion matrix (rows true, cols pred):\n")
            for row in s["mean_confusion_matrix"]:
                f.write("   " + " ".join(f"{v:7.1f}" for v in row) + "\n")
            f.write("\n")
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig, axes = plt.subplots(1, 2, figsize=(9, 4))
    for ax, (cond, s) in zip(axes, summary["conditions"].items()):
        cm = np.array(s["mean_confusion_matrix"])
        ax.imshow(cm, cmap="Blues")
        ax.set_xticks(range(4), CLASSES, rotation=30, ha="right")
        ax.set_yticks(range(4), CLASSES)
        ax.set_title(f"{cond}\nacc {s['accuracy']['mean']:.3f}", fontsize=9)
        for i in range(4):
            for j in range(4):
                ax.text(j, i, f"{cm[i, j]:.0f}", ha="center", va="center", color="white" if cm[i, j] > cm.max() / 2 else "black")
    fig.tight_layout()
    fig.savefig(args.out_dir / "confusion_matrices.png", dpi=120)
    print(json.dumps({c: {"acc_mean": s["accuracy"]["mean"], "macro_f1_mean": s["macro_f1"]["mean"]} for c, s in summary["conditions"].items()}, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
